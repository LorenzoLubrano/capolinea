/**
 * Domain model. Pure data: no React, no storage, no formatting.
 *
 * Conventions
 * - Amounts are integer minor units (cents) paired with an ISO 4217 currency code.
 * - Calendar dates are local dates as `YYYY-MM-DD` strings; timestamps are ISO UTC strings.
 * - Every persisted record carries audit fields and a reserved `ownerId` for future multi-user sync.
 */

export type Id = string;
export type CurrencyCode = string;
/** Local calendar date, `YYYY-MM-DD`. */
export type LocalDate = string;
/** ISO 8601 UTC timestamp. */
export type Timestamp = string;

export interface RecordMeta {
  id: Id;
  createdAt: Timestamp;
  updatedAt: Timestamp;
  /** Soft delete, kept for future sync. */
  deletedAt?: Timestamp;
  /** Reserved for future multi-user support. */
  ownerId?: Id;
}

export type AccountType = 'bank' | 'ewallet' | 'cash' | 'credit_card' | 'savings' | 'other';

export interface Account extends RecordMeta {
  name: string;
  type: AccountType;
  currency: CurrencyCode;
  openingBalanceMinor: number;
  color: string;
  icon?: string;
  includeInTotal: boolean;
  archived: boolean;
  sortOrder: number;
}

export type CategoryKind = 'expense' | 'income';

export interface Category extends RecordMeta {
  name: string;
  kind: CategoryKind;
  icon: string;
  color: string;
  parentId?: Id;
  isDefault: boolean;
  archived: boolean;
  sortOrder: number;
}

export type TransactionType = 'expense' | 'income' | 'transfer' | 'refund';

export type PaymentMethod = 'card' | 'cash' | 'bank_transfer' | 'wallet' | 'other';

export type Necessity = 'need' | 'want';

export interface Person extends RecordMeta {
  name: string;
  /** The app user. Exactly one person has this flag. */
  isMe: boolean;
}

export interface SplitShare {
  personId: Id;
  amountMinor: number;
  settled: boolean;
  settledAt?: LocalDate;
}

export interface Transaction extends RecordMeta {
  type: TransactionType;
  /** Always positive; `type` gives the direction. */
  amountMinor: number;
  currency: CurrencyCode;
  date: LocalDate;
  accountId: Id;
  /** Destination account, transfers only. */
  toAccountId?: Id;
  categoryId?: Id;
  subcategoryId?: Id;
  merchant?: string;
  description?: string;
  notes?: string;
  tags: string[];
  paymentMethod?: PaymentMethod;
  receiptUri?: string;
  necessity?: Necessity;
  isRecurring: boolean;
  /** Set on charges generated by a subscription. */
  subscriptionId?: Id;
  /** Billing date the generated charge belongs to. */
  occurrenceDate?: LocalDate;
  /** True once the user edits a generated charge. */
  editedAfterGeneration?: boolean;
  /** Refunds point at the original expense. */
  refundOfId?: Id;
  paidByPersonId?: Id;
  /** Present when the expense is split; shares sum to `amountMinor`. */
  split?: SplitShare[];
}

export type FrequencyUnit = 'week' | 'month' | 'year';

export interface Frequency {
  unit: FrequencyUnit;
  /** Every N units: monthly = 1 month, quarterly = 3 months. */
  interval: number;
}

export interface Subscription extends RecordMeta {
  name: string;
  amountMinor: number;
  currency: CurrencyCode;
  frequency: Frequency;
  /** First billing date; later dates are computed from it so day 31 survives short months. */
  anchorDate: LocalDate;
  /** Next charge not generated yet. */
  nextBillingDate: LocalDate;
  startDate: LocalDate;
  endDate?: LocalDate;
  categoryId: Id;
  accountId: Id;
  notes?: string;
  active: boolean;
}

export type BudgetScope = 'global' | 'category';

export interface Budget extends RecordMeta {
  scope: BudgetScope;
  categoryId?: Id;
  amountMinor: number;
  currency: CurrencyCode;
  /** First month the budget applies to, `YYYY-MM`. */
  fromMonth: string;
}

export interface GoalContribution {
  id: Id;
  date: LocalDate;
  amountMinor: number;
}

export interface Goal extends RecordMeta {
  name: string;
  icon: string;
  color: string;
  targetMinor: number;
  currency: CurrencyCode;
  targetDate?: LocalDate;
  accountId?: Id;
  contributions: GoalContribution[];
}
